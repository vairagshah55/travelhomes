/**
 * Generates the slim location assets served to the browser.
 *
 * Input  : data/countries_states_cities.json  (36.8 MB — the full dr5hn dataset,
 *          kept out of apps/web/public so Vite never copies it into dist/)
 * Output : apps/web/src/data/countries.ts        (~13 KB — every country, bundled)
 *          apps/web/public/locations/<ISO2>.json (one per country, states + cities)
 *
 * The country list is *bundled* rather than fetched: it is the same 13 KB either
 * way, but bundling keeps every country <select> and the phone dial-code picker
 * synchronous (no loading state, no flash of an empty dropdown) and lets us drop
 * the `country-state-city` package, which shipped a 331 KB chunk to produce
 * exactly these three fields.
 *
 * Why: the full file used to live in public/ and was fetched wholesale by 8 pages
 * (register, checkout, all 3 onboarding flows, add/edit offering). That shipped
 * 3.5 MB gzipped and blocked the main thread for seconds in JSON.parse, to read
 * one country's state list. Now the country dropdown costs 13 KB and the selected
 * country's states/cities are fetched on demand (~40 KB gzip for India).
 *
 * The emitted shapes deliberately mirror the original objects — `states[].name`
 * and `states[].cities[].name` — so every existing call site keeps working
 * unchanged. Only the fields nothing reads (translations, timezones, currency,
 * lat/long, emoji, …) are dropped.
 *
 * Run: npm run build:locations
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "data", "countries_states_cities.json");
const OUT_DIR = path.join(root, "apps", "web", "public", "locations");
const TS_OUT = path.join(root, "apps", "web", "src", "data", "countries.ts");

if (!fs.existsSync(SRC)) {
  console.error(`[locations] missing source dataset: ${SRC}`);
  process.exit(1);
}

const countries = JSON.parse(fs.readFileSync(SRC, "utf8"));
fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const writeJSON = (file, value) => {
  fs.writeFileSync(path.join(OUT_DIR, file), JSON.stringify(value));
  return fs.statSync(path.join(OUT_DIR, file)).size;
};

// The bundled list carries only what a country <select> and a dial-code picker
// need. Sorted by name so the dropdowns read alphabetically.
const index = countries
  .filter((c) => c.iso2)
  .map((c) => ({
    name: c.name,
    iso2: c.iso2,
    phonecode: String(c.phonecode ?? "").replace(/^\+/, ""),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

fs.mkdirSync(path.dirname(TS_OUT), { recursive: true });
fs.writeFileSync(
  TS_OUT,
  `// GENERATED by scripts/build-location-data.mjs — do not edit by hand.
// Run \`npm run build:locations\` to regenerate from data/countries_states_cities.json.
//
// Bundled (not fetched) so country dropdowns and the phone dial-code picker
// render synchronously. States and cities are NOT here — they are fetched per
// country from /locations/<ISO2>.json by useCountriesData().

export interface CountryEntry {
  /** Display name, e.g. "India". Also the key every form stores. */
  name: string;
  /** ISO 3166-1 alpha-2, e.g. "IN". Used to locate /locations/<ISO2>.json. */
  iso2: string;
  /** International dialling prefix without "+", e.g. "91". */
  phonecode: string;
}

export const COUNTRIES: readonly CountryEntry[] = ${JSON.stringify(index, null, 2)};

/** Look up a country by its display name (the value forms persist). */
export const countryByName = (name?: string | null): CountryEntry | undefined =>
  name ? COUNTRIES.find((c) => c.name === name) : undefined;
`,
);
const indexBytes = fs.statSync(TS_OUT).size;

let detailBytes = 0;
let biggest = { iso2: "", bytes: 0 };
for (const c of countries) {
  if (!c.iso2) continue;
  const bytes = writeJSON(`${c.iso2}.json`, {
    name: c.name,
    iso2: c.iso2,
    phonecode: String(c.phonecode ?? "").replace(/^\+/, ""),
    states: (c.states || []).map((s) => ({
      name: s.name,
      cities: (s.cities || []).map((city) => ({ name: city.name })),
    })),
  });
  detailBytes += bytes;
  if (bytes > biggest.bytes) biggest = { iso2: c.iso2, bytes };
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`[locations] source          ${kb(fs.statSync(SRC).size)}  (not served)`);
console.log(`[locations] countries.ts    ${kb(indexBytes)}  (${index.length} countries, bundled)`);
console.log(`[locations] per-country     ${kb(detailBytes)} across ${index.length} files`);
console.log(`[locations] largest         ${biggest.iso2}.json ${kb(biggest.bytes)}`);
console.log(`[locations] India           ${kb(fs.statSync(path.join(OUT_DIR, "IN.json")).size)}`);
console.log(`[locations] a visitor downloads the bundled list + one country file.`);
